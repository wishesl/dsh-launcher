func TestParseSums(t *testing.T) {
	body := strings.Join([]string{
		"# generated by CI",
		strings.Repeat("a", 64) + "  dsh-launcher-windows-amd64.exe",
		strings.Repeat("b", 64) + " *dsh-launcher-linux-amd64.tar.gz",
		strings.Repeat("c", 64) + "  ./dsh-launcher-darwin-arm64.zip",
		"deadbeef  short-hash-should-be-ignored",
	}, "\n")

	if got := parseSums(body, "dsh-launcher-windows-amd64.exe"); got != strings.Repeat("a", 64) {
		t.Errorf("windows 哈希 = %q", got)
	}
	if got := parseSums(body, "dsh-launcher-linux-amd64.tar.gz"); got != strings.Repeat("b", 64) {
		t.Errorf("带 * 前缀的二进制模式没解析出来: %q", got)
	}
	if got := parseSums(body, "dsh-launcher-darwin-arm64.zip"); got != strings.Repeat("c", 64) {
		t.Errorf("带路径前缀的条目没解析出来: %q", got)
	}
	if got := parseSums(body, "not-there.exe"); got != "" {
		t.Errorf("缺失条目应返回空串, got %q", got)
	}
}

func TestDownloadToFileHashAndSize(t *testing.T) {
	payload := bytes.Repeat([]byte("dsh-launcher"), 512)
	want := sha256.Sum256(payload)
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Content-Length", strconv.Itoa(len(payload)))
		_, _ = w.Write(payload)
	}))
	defer srv.Close()

	dest := filepath.Join(t.TempDir(), "pkg.part")
	got, err := downloadToFile(context.Background(), srv.Client(), srv.URL, dest, int64(len(payload)), nil)
	if err != nil {
		t.Fatalf("downloadToFile: %v", err)
	}
	if wantHex := hex.EncodeToString(want[:]); got != wantHex {
		t.Errorf("sha256 = %s, want %s", got, wantHex)
	}
	if st, _ := os.Stat(dest); st == nil || st.Size() != int64(len(payload)) {
		t.Errorf("落盘大小不对: %v", st)
	}

	// 期望大小与实际不符（例如被代理截断）必须报错，不能"算出一个哈希就算成功"
	if _, err := downloadToFile(context.Background(), srv.Client(), srv.URL, dest+".2", int64(len(payload)+7), nil); err == nil {
		t.Error("大小不符时应报错")
	}
}

func TestFetchExpectedSum(t *testing.T) {
	sum := strings.Repeat("d", 64)
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/SHA256SUMS" {
			w.WriteHeader(http.StatusNotFound)
			return
		}
		_, _ = w.Write([]byte(sum + "  dsh-launcher-windows-amd64.exe\n"))
	}))
	defer srv.Close()

	got, err := fetchExpectedSum(context.Background(), srv.Client(), srv.URL+"/SHA256SUMS", "dsh-launcher-windows-amd64.exe")
	if err != nil || got != sum {
		t.Fatalf("fetchExpectedSum = (%q,%v)", got, err)
	}
	// 列表里没有这个资产 → 必须报错（没有校验就不装）
	if _, err := fetchExpectedSum(context.Background(), srv.Client(), srv.URL+"/SHA256SUMS", "other.exe"); err == nil {
		t.Error("找不到对应哈希时应报错")
	}
	if _, err := fetchExpectedSum(context.Background(), srv.Client(), srv.URL+"/missing", "x.exe"); err == nil {
		t.Error("HTTP 404 时应报错")
	}
}

func TestApplyUpdateExecutableSwapsAndRollsBack(t *testing.T) {
	dir := t.TempDir()
	self := filepath.Join(dir, "dsh-launcher.exe")
	newer := filepath.Join(dir, "downloaded.exe")
	if err := os.WriteFile(self, []byte("OLD"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(newer, []byte("NEW"), 0o755); err != nil {
		t.Fatal(err)
	}

	if err := applyUpdateExecutable(self, newer); err != nil {
		t.Fatalf("applyUpdateExecutable: %v", err)
	}
	got, err := os.ReadFile(self)
	if err != nil || string(got) != "NEW" {
		t.Fatalf("原路径上应是新版本, got %q err=%v", got, err)
	}

	// 回滚路径：新文件不存在 → 报错，且原路径必须还是原来的可执行文件
	if err := os.WriteFile(self, []byte("OLD"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := applyUpdateExecutable(self, filepath.Join(dir, "missing.exe")); err == nil {
		t.Fatal("新文件缺失时应报错")
	}
	got, err = os.ReadFile(self)
	if err != nil || string(got) != "OLD" {
		t.Fatalf("回滚失败：原路径应还是旧版本, got %q err=%v", got, err)
	}
	if _, err := os.Stat(self + ".old"); !os.IsNotExist(err) {
		t.Errorf("回滚后不该留下 .old: %v", err)
	}
}

