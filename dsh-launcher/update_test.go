func TestUpdateAssetName(t *testing.T) {
	cases := []struct {
		goos, goarch string
		want         string
		ok           bool
	}{
		{"windows", "amd64", "dsh-launcher-windows-amd64.exe", true},
		{"darwin", "arm64", "dsh-launcher-darwin-arm64.zip", true},
		{"darwin", "amd64", "dsh-launcher-darwin-amd64.zip", true},
		{"linux", "amd64", "dsh-launcher-linux-amd64.tar.gz", true},
		{"windows", "arm64", "", false}, // CI 没产出这个组合 → 只能走下载页
		{"linux", "arm64", "", false},
	}
	for _, c := range cases {
		got, ok := updateAssetName(c.goos, c.goarch)
		if got != c.want || ok != c.ok {
			t.Errorf("updateAssetName(%s/%s) = (%q,%v), want (%q,%v)", c.goos, c.goarch, got, ok, c.want, c.ok)
		}
	}
}

func TestBuildLauncherReleaseHasUpdate(t *testing.T) {
	rel := &ghRelease{
		TagName:     "v0.6.0",
		Name:        "v0.6.0",
		Body:        "  本轮变化：…  ",
		PublishedAt: "2026-09-13T05:57:11Z",
		HTMLURL:     "https://github.com/wishesl/dsh-launcher/releases/tag/v0.6.0",
		Assets: []ghAsset{
			{Name: "dsh-launcher-windows-amd64.exe", Size: 100, URL: "https://example.test/a.exe"},
			{Name: sumsAssetName, Size: 64, URL: "https://example.test/SHA256SUMS"},
		},
	}
	out := buildLauncherRelease(rel, "0.5.1", runtime.GOOS, runtime.GOARCH, "")
	if !out.Comparable || !out.HasUpdate {
		t.Fatalf("expected comparable+hasUpdate, got %+v", out)
	}
	if out.Latest != "0.6.0" {
		t.Errorf("Latest = %q, want 0.6.0 (v 前缀要去掉)", out.Latest)
	}
	if out.Notes != "本轮变化：…" {
		t.Errorf("Notes 应去掉首尾空白, got %q", out.Notes)
	}
	// Windows 上资产齐备 → 可应用内更新；其它平台按 updateAppliable 的结论。
	wantSupported := runtime.GOOS == "windows"
	if out.Supported != wantSupported {
		t.Errorf("Supported = %v, want %v (%s/%s)", out.Supported, wantSupported, runtime.GOOS, runtime.GOARCH)
	}
	if out.Supported && out.Asset.Name == "" {
		t.Error("Supported 为真时必须有本平台资产")
	}
	if out.sumsURL == "" {
		t.Error("应记录 SHA256SUMS 的地址（下载校验要用）")
	}
}

func TestBuildLauncherReleaseThreeStates(t *testing.T) {
	base := func() *ghRelease {
		return &ghRelease{
			TagName: "v0.6.0",
			Assets: []ghAsset{
				{Name: "dsh-launcher-windows-amd64.exe", Size: 100, URL: "https://example.test/a.exe"},
				{Name: sumsAssetName, Size: 64, URL: "https://example.test/SHA256SUMS"},
			},
		}
	}

	// ① dev 构建：不参与比较（但也别谎报"有更新"）
	dev := buildLauncherRelease(base(), "dev", runtime.GOOS, runtime.GOARCH, "")
	if dev.Comparable || dev.HasUpdate {
		t.Errorf("dev 构建不应参与比较: %+v", dev)
	}

	// ② 已是最新
	same := buildLauncherRelease(base(), "0.6.0", runtime.GOOS, runtime.GOARCH, "")
	if !same.Comparable || same.HasUpdate {
		t.Errorf("同版本不应报有更新: %+v", same)
	}

	// ③ 本地比线上新（预发布尝鲜）→ 不提示更新
	ahead := buildLauncherRelease(base(), "0.6.1", runtime.GOOS, runtime.GOARCH, "")
	if ahead.HasUpdate {
		t.Errorf("本地更高时不应报有更新: %+v", ahead)
	}

	// ④ 没有 SHA256SUMS → 不支持应用内更新，且给出人话原因
	noSums := base()
	noSums.Assets = noSums.Assets[:1]
	ns := buildLauncherRelease(noSums, "0.5.1", runtime.GOOS, runtime.GOARCH, "")
	if ns.Supported || !strings.Contains(ns.SupportNote, sumsAssetName) {
		t.Errorf("缺校验和时不该支持应用内更新: %+v", ns)
	}

	// ⑤ 用户点过「跳过此版本」
	skip := buildLauncherRelease(base(), "0.5.1", runtime.GOOS, runtime.GOARCH, "0.6.0")
	if !skip.Skipped {
		t.Errorf("skippedVersion 命中时应标记 Skipped: %+v", skip)
	}
}

