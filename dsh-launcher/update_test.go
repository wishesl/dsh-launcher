// fakeGitHub 起一个假 GitHub：/repos/o/r/releases/latest + 资产 + SHA256SUMS。
// tamper=true 时故意把校验和写错（验证"校验不过就绝不安装"）。
func fakeGitHub(t *testing.T, payload []byte, tamper bool) (base string, downloads *int32) {
	t.Helper()
	assetName, ok := updateAssetName(runtime.GOOS, runtime.GOARCH)
	if !ok {
		t.Skipf("当前平台 %s/%s 没有 CI 产物，跳过", runtime.GOOS, runtime.GOARCH)
	}
	sum := sha256.Sum256(payload)
	sumHex := hex.EncodeToString(sum[:])
	if tamper {
		sumHex = strings.Repeat("0", 64)
	}
	var hits int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/repos/o/r/releases/latest":
			_ = json.NewEncoder(w).Encode(map[string]interface{}{
				"tag_name":     "v0.6.0",
				"name":         "v0.6.0",
				"body":         "本轮变化",
				"published_at": "2026-09-13T05:57:11Z",
				"html_url":     "https://example.test/releases/tag/v0.6.0",
				"assets": []map[string]interface{}{
					{"name": assetName, "size": len(payload), "browser_download_url": "http://" + r.Host + "/dl/" + assetName},
					{"name": sumsAssetName, "size": 72, "browser_download_url": "http://" + r.Host + "/dl/" + sumsAssetName},
				},
			})
		case "/dl/" + assetName:
			atomic.AddInt32(&hits, 1)
			_, _ = w.Write(payload)
		case "/dl/" + sumsAssetName:
			_, _ = w.Write([]byte(sumHex + "  " + assetName + "\n"))
		default:
			w.WriteHeader(http.StatusNotFound)
		}
	}))
	t.Cleanup(srv.Close)
	return srv.URL, &hits
}

// newUpdateTestApp 造一个"配置目录在临时目录里"的 App，并把包级变量临时改掉：
// 假 GitHub + 假 self（绝不能让单测把测试二进制自己替换掉）。
func newUpdateTestApp(t *testing.T, apiBase, self string) *App {
	t.Helper()
	tmp := t.TempDir()
	oldAPI, oldSelf, oldVersion := updateAPIBase, updateSelfPath, version
	updateAPIBase = apiBase
	updateSelfPath = func() (string, error) { return self, nil }
	version = "0.5.1"
	oldApplied := updateApplied.Load()
	t.Cleanup(func() {
		updateAPIBase, updateSelfPath, version = oldAPI, oldSelf, oldVersion
		updateApplied.Store(oldApplied)
		appliedVersion.Store("")
		updCache.Lock()
		updCache.release, updCache.etag, updCache.at = nil, "", time.Time{}
		updCache.Unlock()
	})
	a := &App{
		settings: &settingsStore{path: filepath.Join(tmp, "settings.json")},
		store:    &instanceStore{path: filepath.Join(tmp, "instances.json")},
	}
	a.settings.setUpdateSettings(true, false, "", "o/r")
	return a
}

// TestUpdateFullFlow 跑完整链路：检查 → 下载 → sha256 校验 → 就地替换 → "已就位"。
// 这是 M2 的核心验收（真机上再跑一次，见方案 §7）。
func TestUpdateFullFlow(t *testing.T) {
	if runtime.GOOS != "windows" {
		t.Skip("应用内就地替换目前只在 Windows 实现（M4 才做跨平台）")
	}
	payload := []byte("NEW-LAUNCHER-BINARY-PAYLOAD")
	base, downloads := fakeGitHub(t, payload, false)

	self := filepath.Join(t.TempDir(), "dsh-launcher.exe")
	if err := os.WriteFile(self, []byte("OLD-BINARY"), 0o755); err != nil {
		t.Fatal(err)
	}
	a := newUpdateTestApp(t, base, self)

	rel := a.CheckLauncherUpdate(true)
	if rel.Err != "" {
		t.Fatalf("检查更新失败: %s", rel.Err)
	}
	if !rel.HasUpdate || !rel.Comparable {
		t.Fatalf("应判定为有更新: %+v", rel)
	}
	if !rel.Supported || rel.Asset.Name == "" {
		t.Fatalf("资产齐备时应支持应用内更新: %+v", rel)
	}
	if rel.Latest != "0.6.0" || rel.Current != "0.5.1" {
		t.Fatalf("版本号解析不对: %+v", rel)
	}

	if err := a.DownloadLauncherUpdate(); err != nil {
		t.Fatalf("下载安装失败: %v", err)
	}
	got, err := os.ReadFile(self)
	if err != nil {
		t.Fatalf("替换后读不到 exe: %v", err)
	}
	if !bytes.Equal(got, payload) {
		t.Fatalf("exe 未被替换成新版本: %q", got)
	}
	if n := atomic.LoadInt32(downloads); n != 1 {
		t.Errorf("资产应只下载一次, got %d", n)
	}
	if v := a.UpdateAppliedVersion(); v != "0.6.0" {
		t.Errorf("已就位版本 = %q, want 0.6.0", v)
	}
	if a.UpdateOpRunning() {
		t.Error("结束之后不该还显示运行中")
	}
}

// TestUpdateRefusesBadChecksum 校验和不对时必须拒绝安装，并且**不动**原 exe。
func TestUpdateRefusesBadChecksum(t *testing.T) {
	if runtime.GOOS != "windows" {
		t.Skip("应用内就地替换目前只在 Windows 实现")
	}
	payload := []byte("TAMPERED-PAYLOAD")
	base, _ := fakeGitHub(t, payload, true)

	self := filepath.Join(t.TempDir(), "dsh-launcher.exe")
	if err := os.WriteFile(self, []byte("OLD-BINARY"), 0o755); err != nil {
		t.Fatal(err)
	}
	a := newUpdateTestApp(t, base, self)

	if err := a.DownloadLauncherUpdate(); err == nil {
		t.Fatal("校验和不匹配时必须报错")
	}
	got, err := os.ReadFile(self)
	if err != nil || string(got) != "OLD-BINARY" {
		t.Fatalf("校验失败时不该动原 exe, got %q err=%v", got, err)
	}
	if v := a.UpdateAppliedVersion(); v != "" {
		t.Errorf("校验失败不该标记已就位, got %q", v)
	}
}
